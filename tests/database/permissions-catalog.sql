-- LOCAL ONLY; actual PostgreSQL catalog checks, with all probes rolled back.
begin;
set local search_path=public,extensions;
do $$ begin
  if current_database() not like 'filminhere_audit%' then
    raise exception 'Disposable audit database required';
  end if;
end $$;
select no_plan();

select is((select count(*)::integer from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r'),32,'All 32 application tables reconstructed');
select is((select count(*)::integer from pg_class c join pg_namespace n on n.oid=c.relnamespace
  where n.nspname='public' and c.relkind='r' and not c.relrowsecurity),0,'Every application table retains RLS');
select is((select count(*)::integer from public.profiles),4,'Auth signup trigger created all fixture profiles');
select ok((select user_role::text='host' from public.profiles
  where id='22222222-2222-4222-8222-222222222222'),'Signup trigger preserves supported host role');
select ok((select prosecdef and proowner='postgres'::regrole from pg_proc
  where oid='private.sync_approved_host_listing_public()'::regprocedure),'Projection trigger retains trusted definer owner');

-- Catalogs and the two new public tables expose only SELECT to browser roles.
select ok(has_table_privilege(r, t, 'SELECT'), r||' SELECT '||t)
from unnest(array['anon','authenticated']) r
cross join unnest(array['listing_types','departments','categories','listing_attributes',
  'shoot_types','shoot_requirements','resource_relationships','distribution_destinations',
  'destination_field_mappings','destination_asset_requirements','project_statuses',
  'project_deliverables','project_rights_checklist','approved_host_listings_public','translation_roots']) t;
select ok(not has_table_privilege(r,t,p), r||' denied '||p||' '||t)
from unnest(array['anon','authenticated']) r
cross join unnest(array['listing_types','departments','categories','listing_attributes',
  'shoot_types','shoot_requirements','resource_relationships','distribution_destinations',
  'destination_field_mappings','destination_asset_requirements','project_statuses',
  'project_deliverables','project_rights_checklist','approved_host_listings_public','translation_roots']) t
cross join unnest(array['INSERT','UPDATE','DELETE','TRUNCATE','REFERENCES','TRIGGER','MAINTAIN']) p;

select ok(not has_sequence_privilege(r,c.oid,p),r||' denied sequence '||p||' '||c.relname)
from pg_class c join pg_namespace n on n.oid=c.relnamespace
cross join unnest(array['anon','authenticated']) r
cross join unnest(array['USAGE','SELECT','UPDATE']) p
where n.nspname='public' and c.relkind='S';
select ok(not has_sequence_privilege('service_role','public.translation_roots_id_seq',p),
  'service role denied unused glossary sequence '||p)
from unnest(array['USAGE','SELECT','UPDATE']) p;
select ok(not has_table_privilege('service_role',t,p),'service role denied unused '||p||' '||t)
from unnest(array['approved_host_listings_public','translation_roots']) t
cross join unnest(array['SELECT','INSERT','UPDATE','DELETE','TRUNCATE','REFERENCES','TRIGGER','MAINTAIN']) p;

-- A BYPASSRLS role still needs object privileges. Explicit existing backend grants remain.
select ok(has_table_privilege('service_role',t,p),'Required service privilege '||p||' '||t)
from (values ('booking_requests','SELECT'),('booking_requests','UPDATE'),
  ('host_listing_submissions','SELECT'),('host_listing_submissions','UPDATE'),
  ('booking_messages','SELECT'),('booking_messages','INSERT'),
  ('booking_offers','SELECT'),('booking_offers','INSERT'),('booking_offers','UPDATE')) v(t,p);
select ok(has_table_privilege('authenticated',t,'INSERT'),'Preserved authenticated INSERT '||t)
from unnest(array['booking_requests','host_listing_submissions','policy_acceptances']) t;
select ok(has_function_privilege('service_role',f,'EXECUTE'),'Preserved service RPC '||f)
from unnest(array['public.finalize_booking_acceptance(uuid,uuid,text)',
                 'public.persist_host_constraints(uuid,uuid,jsonb,text)']) f;
select ok(not has_function_privilege(r,f,'EXECUTE'),r||' denied service RPC '||f)
from unnest(array['anon','authenticated']) r
cross join unnest(array['public.finalize_booking_acceptance(uuid,uuid,text)',
                 'public.persist_host_constraints(uuid,uuid,jsonb,text)']) f;
select ok(has_function_privilege('authenticated','private.current_user_is_admin()','EXECUTE'),
  'Authenticated RLS admin helper still executable');
select ok(not has_function_privilege(r,'public.handle_new_auth_user_profile()','EXECUTE'),
  r||' cannot call signup trigger helper') from unnest(array['anon','authenticated']) r;

-- Fresh probes catch the false pass where the evidence baseline restores defaults.
create table public.permissions_future_probe(id bigint generated by default as identity);
create function public.permissions_future_function() returns integer language sql as 'select 1';
create function auth.permissions_future_function() returns integer language sql as 'select 1';
select ok(not has_table_privilege(r,'public.permissions_future_probe',p),
  'Future table: '||r||' denied '||p)
from unnest(array['anon','authenticated','service_role']) r
cross join unnest(array['SELECT','INSERT','UPDATE','DELETE','TRUNCATE','REFERENCES','TRIGGER','MAINTAIN']) p;
select ok(not has_sequence_privilege(r,'public.permissions_future_probe_id_seq',p),
  'Future sequence: '||r||' denied '||p)
from unnest(array['anon','authenticated','service_role']) r
cross join unnest(array['USAGE','SELECT','UPDATE']) p;
select ok(not has_function_privilege(r,f,'EXECUTE'),'Future function: '||r||' denied '||f)
from unnest(array['anon','authenticated','service_role']) r
cross join unnest(array['public.permissions_future_function()','auth.permissions_future_function()']) f;

select * from finish();
rollback;
